@Immutable
data class KeyboardColors(
    /** 鍵盤和候選列的底色。 */
    val background: Color,
    /** 字母鍵、數字鍵、空白鍵和「，」「。」。 */
    val key: Color,
    /** Shift、Delete、Emoji、123、Enter；也用作首選字的底色。 */
    val functionKey: Color,
    /** 按下時的底色：所有按鍵、候選字和工具列。 */
    val pressedKey: Color,
    /** 主標示、按鍵圖示和候選字。 */
    val label: Color,
    /** 角落小字、工具列和候選列最右的按鈕。 */
    val secondaryLabel: Color,
    /** 記憶字的綠色。 */
    val remembered: Color,
    /** 記憶字的淺綠底（深色主題是深綠底），候選列和候選字格都用。 */
    val rememberedChip: Color,
    /** 「空白鍵選中文」模式下，首選字剛好是記憶字時的底色；和首選字的灰底一樣比一般的底色突出一級。 */
    val rememberedChipMarked: Color,
    /** 按鍵底部 1dp 的實色陰影。 */
    val keyShadow: Color,
    /** 候選列的分隔線。 */
    val divider: Color,
    /** 大寫鎖定時 Shift 鍵的底色和圖示。 */
    val accent: Color,
    val onAccent: Color,
    /** 單次大寫時 Shift 鍵的底色和圖示。 */
    val accentSoft: Color,
    val onAccentSoft: Color,
    /** 按鍵放大預覽的底色；深色時比按鍵亮一級。 */
    val preview: Color,
    /** 漸變主題的底色，鋪滿整個鍵盤；這時 background 是漸變最上面的顏色。純色主題是 null。 */
    val gradient: KeyboardGradient? = null,
)

/**
 * 漸變的底色：色位平均分佈，角度跟 CSS 的 linear-gradient（180 是由上到下，135 是由左上到右下）。
 * 半透明的按鍵疊在上面，讓漸變透出來。
 */
@Immutable
data class KeyboardGradient(val angle: Float, val colors: List<Color>) {

    /** 鋪滿 size 時漸變線的起點和終點：和 CSS 一樣穿過中心，兩端剛好碰到最遠的兩個角。 */
    fun line(size: Size): Pair<Offset, Offset> {
        val radians = Math.toRadians(angle.toDouble())
        val direction = Offset(sin(radians).toFloat(), -cos(radians).toFloat())
        val half = (abs(size.width * direction.x) + abs(size.height * direction.y)) / 2
        return size.center - direction * half to size.center + direction * half
    }
}

